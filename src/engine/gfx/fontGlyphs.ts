/** Zeichen, die auf vorhandene Glyphen abgebildet werden. */
export const ALIASES: Record<string, string> = { '’': "'", '‘': "'", '”': '"', '—': '–', '«': '"', '»': '"' };

export const SPACE_WIDTH = 3;
export const LETTER_SPACING = 1;

export interface GlyphBitmap {
  char: string;
  width: number;
  buf: PixBuf; // CELL_H hoch, width breit, Pixel = Farbe oder null
}

export function glyphBitmap(char: string, color = '#ffffff'): GlyphBitmap {
  if (char === ' ') return { char, width: SPACE_WIDTH, buf: new PixBuf(SPACE_WIDTH, CELL_H) };
  const g = GLYPHS[char] ?? GLYPHS[ALIASES[char] ?? '?'] ?? GLYPHS['?'];
  const [top, spec] = g;
  const lines = spec.split('/');
  const width = Math.max(...lines.map((l) => l.length));
  const buf = new PixBuf(width, CELL_H);
  lines.forEach((line, y) => [...line].forEach((ch, x) => ch === '#' && buf.set(x, top + y, color)));
  return { char, width, buf };
}

/** Breite eines Textes in Pixeln (für Zeilenumbruch und Zentrierung). */
export function measureText(text: string): number {
  let w = 0;
  for (const ch of text) w += glyphBitmap(ch).width + LETTER_SPACING;
  return Math.max(0, w - LETTER_SPACING);
}

/** Bricht Text an Wortgrenzen um. Harte Umbrüche mit \n bleiben erhalten. */
export function wrapText(text: string, maxWidth: number): string[] {
  const out: string[] = [];
  for (const para of text.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const test = line ? `${line} ${word}` : word;
      if (measureText(test) <= maxWidth || !line) line = test;
      else {
        out.push(line);
        line = word;
      }
    }
    out.push(line);
  }
  return out;
}

export function allFontChars(): string[] {
  return [' ', ...Object.keys(GLYPHS)];
}
